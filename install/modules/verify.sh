#!/usr/bin/env bash
# Final check of the installed environment.
#
# The installer used to print "installed successfully" even when required
# packages failed (FAILED_PKGS was only listed below the success line), so a
# partial install looked complete and ended in an empty Hyprland session.
# verify_installation decides the final status from what is actually present.

INSTALL_INCOMPLETE=false
VERIFY_ERRORS=()
VERIFY_WARNINGS=()

# Packages without which the shell cannot start or render the desktop.
CRITICAL_PKGS=("quickshell" "qt6-multimedia" "qt6-wayland" "qt6-imageformats" "jq" "python" "kitty")

# First Hyprland release that reads hyprland.lua. Older versions ignore the
# Lua configuration shipped by Serpantinum and start with an autogenerated
# config: no autostart, so no shell and no wallpaper.
MIN_HYPRLAND_LUA_VERSION="0.55.0"

# Resolves the shell's QML types the way Quickshell does (qs: URLs, scanned
# directories only). A type that does not resolve aborts the whole config with
# "X is not a type" and quickshell exit code 255.
VERIFY_QML_CHECK="$(dirname "$(realpath "${BASH_SOURCE[0]}")")/qml_check.py"

hyprland_version() {
    local bin
    for bin in Hyprland hyprland; do
        command -v "$bin" >/dev/null 2>&1 || continue
        "$bin" --version 2>/dev/null | grep -oE '[0-9]+\.[0-9]+\.[0-9]+' | head -n 1
        return 0
    done
    return 1
}

version_at_least() {
    [ -n "$1" ] && [ "$(printf '%s\n%s\n' "$2" "$1" | sort -V | head -n 1)" = "$2" ]
}

verify_error() {
    VERIFY_ERRORS+=("$1")
    INSTALL_INCOMPLETE=true
}

verify_warning() {
    VERIFY_WARNINGS+=("$1")
}

ensure_hyprland_lua_support() {
    local version
    version="$(hyprland_version)" || return 0
    version_at_least "$version" "$MIN_HYPRLAND_LUA_VERSION" && return 0
    echo -e "\n\e[33m[ WARN ]\e[0m Hyprland $version cannot read hyprland.lua (needs >= $MIN_HYPRLAND_LUA_VERSION). Trying to upgrade..."
    if declare -f pm_upgrade_hyprland >/dev/null; then
        pm_upgrade_hyprland || true
    fi
    hash -r
}

verify_installation() {
    local target_base="$HOME/.local/share/serpantinum"
    local comp pkg missing version

    VERIFY_ERRORS=()
    VERIFY_WARNINGS=()
    INSTALL_INCOMPLETE=false

    echo -e "\n\e[36m[ INFO ]\e[0m Verifying the installed environment..."

    missing="$(pm_missing_pkgs "${CRITICAL_PKGS[@]}")"
    while IFS= read -r pkg; do
        [ -n "$pkg" ] && verify_error "required package missing: $pkg"
    done <<< "$missing"

    if command -v quickshell >/dev/null 2>&1; then
        if ! quickshell_is_current; then
            verify_error "quickshell $(quickshell_version) is older than $MIN_QUICKSHELL_VERSION"
        fi
    else
        verify_error "quickshell command not found"
    fi

    for comp in "${SELECTED_COMPOSITORS[@]}"; do
        case "$comp" in
            hyprland)
                if ! version="$(hyprland_version)"; then
                    verify_error "Hyprland is not installed"
                elif ! version_at_least "$version" "$MIN_HYPRLAND_LUA_VERSION"; then
                    verify_error "Hyprland $version does not support the Lua config (needs >= $MIN_HYPRLAND_LUA_VERSION); the session would start without the shell"
                fi
                [ -f "$HOME/.config/hypr/hyprland.lua" ] || verify_error "~/.config/hypr/hyprland.lua was not deployed"
                # Hyprland's own dialogs (app not responding, permission
                # prompts). Not used by Serpantinum; Fedora ships it only in
                # COPR, which may need newer hypr* libraries than Fedora's
                # Hyprland, so it is reported instead of installed.
                if ! pm_is_installed hyprland-guiutils 2>/dev/null && ! command -v hyprland-dialog >/dev/null 2>&1; then
                    verify_warning "hyprland-guiutils missing: Hyprland warns about it and its own dialogs (app not responding, permissions) do not open; Serpantinum does not need it. Fedora: sudo dnf copr enable mineiro/hyprland && sudo dnf install hyprland-guiutils"
                fi
                ;;
            mango)
                command -v mango >/dev/null 2>&1 || verify_error "MangoWC is not installed (it needs the Terra repository on Fedora)"
                ;;
            *)
                command -v "$comp" >/dev/null 2>&1 || verify_error "$comp is not installed"
                ;;
        esac
    done

    [ -f "$target_base/src/quickshell/Shell.qml" ] || verify_error "shell files missing in $target_base/src"
    if [ -n "${PROJECT_ROOT:-}" ] && [ -d "$PROJECT_ROOT/src/quickshell" ] && [ -d "$target_base/src/quickshell" ]; then
        if ! diff -rq -x __pycache__ "$PROJECT_ROOT/src/quickshell" "$target_base/src/quickshell" >/dev/null 2>&1; then
            verify_error "installed shell differs from $PROJECT_ROOT/src/quickshell (stale or incomplete copy)"
        fi
    fi
    if [ -f "$target_base/src/quickshell/Shell.qml" ]; then
        local qml_report
        if [ ! -f "$VERIFY_QML_CHECK" ]; then
            verify_error "QML check script missing: $VERIFY_QML_CHECK"
        elif command -v python3 >/dev/null 2>&1 \
            && ! qml_report="$(python3 "$VERIFY_QML_CHECK" "$target_base/src/quickshell" 2>&1)"; then
            verify_error "the shell would not start (quickshell exit 255), unresolved QML types:"$'\n'"$qml_report"
        fi
    fi
    [ -x "$target_base/bin/serpantinumd" ] || verify_error "serpantinumd missing in $target_base/bin"
    if ! command -v serpantinumd >/dev/null 2>&1 && [ ! -x "$HOME/.local/bin/serpantinumd" ]; then
        verify_error "serpantinumd is not linked into ~/.local/bin"
    fi

    command -v ffmpeg >/dev/null 2>&1 || verify_warning "ffmpeg missing: video wallpaper snapshots and Themess wallpaper validation will not work"
    command -v matugen >/dev/null 2>&1 || [ -x "$HOME/.local/bin/matugen" ] || verify_warning "matugen missing: colors will not follow the wallpaper"
    command -v xdg-open >/dev/null 2>&1 || verify_warning "xdg-open missing (xdg-utils): the File Dock widget cannot open files and folders"
    command -v ping >/dev/null 2>&1 || verify_warning "ping missing (iputils): the network widget's optional latency stays empty"
    if command -v rpm >/dev/null 2>&1 && rpm -q ffmpeg-free >/dev/null 2>&1 && ! rpm -q ffmpeg >/dev/null 2>&1; then
        verify_warning "ffmpeg-free is installed: H.264/HEVC (most .mp4/.mov) video wallpapers will not play; WebM (VP9/AV1) works. RPM Fusion 'ffmpeg' adds the codecs."
    fi

    local wp_dir
    wp_dir="$(get_wallpaper_dir)"
    if [ -z "$(find -L "$wp_dir" -maxdepth 1 -type f 2>/dev/null | head -n 1)" ]; then
        verify_warning "wallpaper folder $wp_dir is empty (download failed?); the first start uses a bundled wallpaper"
    fi

    local item
    for item in "${VERIFY_WARNINGS[@]}"; do
        echo -e "  \e[33m[ WARN ]\e[0m $item"
    done
    for item in "${VERIFY_ERRORS[@]}"; do
        echo -e "  \e[31m[ ERROR ]\e[0m $item"
    done
    if [ "$INSTALL_INCOMPLETE" = true ]; then
        echo -e "\n\e[31m[ FAILED ]\e[0m Installation is incomplete. Fix the errors above and run the installer again."
        return 1
    fi
    echo -e "  \e[32m[ OK ]\e[0m Environment verified."
    return 0
}
